"""Run generate_answer + trust scoring over the 10 sample questions in
data/eval/sample_questions.csv and save a report for manual review.

Same "generate, don't grade" spirit as Week 5's run_sample_questions.py --
this is Week 6's manual-review step, not Week 7's scored ablation (which
compares vector-only/graph-only/hybrid retrieval modes against ground
truth over a larger question set).

Usage:
    python eval/run_trust_scores.py
    python eval/run_trust_scores.py --out docs/week6_trust_scores.md
"""

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "generation"))
from common import ENTITIES_CSV, REPO_ROOT, get_logger  # noqa: E402

from generate_answer import answer_question  # noqa: E402
from ollama_client import is_reachable  # noqa: E402
from trust_score import compute_trust_score  # noqa: E402

log = get_logger("run_trust_scores")

SAMPLE_QUESTIONS_CSV = REPO_ROOT / "data" / "eval" / "sample_questions.csv"
DEFAULT_OUT = REPO_ROOT / "docs" / "week6_trust_scores.md"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--questions", type=Path, default=SAMPLE_QUESTIONS_CSV)
    parser.add_argument("--entities", type=Path, default=ENTITIES_CSV)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    if not is_reachable():
        log.info("Ollama not reachable -- see docs/manual_setup_ollama.md")
        sys.exit(1)

    questions_df = pd.read_csv(args.questions, keep_default_na=False)
    entities_df = pd.read_csv(args.entities, keep_default_na=False)

    lines = [
        "# Week 6 trust scores",
        "",
        "Generated by `eval/run_trust_scores.py`. Manual review only -- not "
        "the scored vector/graph/hybrid ablation (that's Week 7).",
        "",
    ]
    scores_for_summary = []

    for _, row in questions_df.iterrows():
        log.info(f"{row['id']}: {row['question']}")
        result = answer_question(row["question"], entities_df)
        scoring = compute_trust_score(result["answer"], result["bundle"])

        lines.append(f"## {row['id']} [{row['category']}]: {row['question']}")
        lines.append("")
        lines.append(f"**Answer:** {result['answer']}")
        lines.append("")
        if scoring["trust_score"] is None:
            lines.append("**Trust score:** N/A (no checkable claims)")
        else:
            lines.append(f"**Trust score:** {scoring['trust_score']:.0%} ({scoring['n_entailed']}/{scoring['n_claims']} claims entailed)")
            scores_for_summary.append(scoring["trust_score"])
        lines.append("")
        for r in scoring["claims"]:
            lines.append(f"- [{r['verdict']}, score={r['score']:.2f}] {r['claim']}")
        lines.append("")

    if scores_for_summary:
        avg = sum(scores_for_summary) / len(scores_for_summary)
        lines.insert(3, f"**Average trust score across {len(scores_for_summary)} scored answers: {avg:.0%}**\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    log.info(f"wrote trust scores for {len(questions_df)} questions to {args.out}")


if __name__ == "__main__":
    main()
